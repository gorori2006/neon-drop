/* ------------------------------------------------------------
   落下速度
     ガイドライン式 (0.8 - (level-1)*0.007) ^ (level-1) 秒/行
   ------------------------------------------------------------ */
function gravityMs(level){
  const lv = Math.min(level, MAX_LEVEL);
  const sec = Math.pow(0.8 - (lv - 1) * 0.007, lv - 1);
  return Math.max(sec * 1000, 16);
}

/* レベルに応じた背景の色相（220 → 一周して戻る） */
function levelHue(level){
  return (220 + (level - 1) * 17) % 360;
}

